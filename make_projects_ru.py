def main():
    with open(os.path.join(BASE, "projects.json"), encoding="utf-8") as f:
        data = json.load(f)
    ru_projects = []
    for p in data["projects"]:
        t = RU[p["slug"]]
        entry = {
            "name": p["name"],
            "slug": p["slug"],
            "section": p["section"],
            "tagline": t["tagline"],
            "status": t["status"],
            "about": t["about"],
            "highlights": t["highlights"],
        }
        if p.get("external"):
            entry["external"] = {
                "url": p["external"]["url"],
                "label": t.get("external_label", p["external"]["label"]),
            }
        if p.get("source_html"):
            entry["has_en_demo"] = True
        ru_projects.append(entry)
    out = {"projects": ru_projects}
    path = os.path.join(BASE, "projects_ru.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print("wrote", path, "-", len(ru_projects), "projects")


if __name__ == "__main__":
    main()
